// Regenerates grammars/php.tmLanguage.json from VS Code's PHP grammar (MIT).
// Saturn takes one grammar per language, so the PHP code grammar (source.php)
// is merged into an HTML-embedding wrapper (text.html.php) as one file.
// Usage: node tools/build-grammar.js
import { writeFile } from 'node:fs/promises';

const SOURCE = 'https://raw.githubusercontent.com/microsoft/vscode/main/extensions/php/syntaxes/php.tmLanguage.json';

const php = await (await fetch(SOURCE)).json();

// "$self" would point at the wrapper root (HTML), so point it at the PHP code instead.
const repository = JSON.parse(JSON.stringify(php.repository).replaceAll('"$self"', '"#php-code"'));
repository['php-code'] = {
  patterns: JSON.parse(JSON.stringify(php.patterns).replaceAll('"$self"', '"#php-code"')),
};
repository['php-tag'] = {
  patterns: [
    {
      begin: '<\\?(?i:php|=)?',
      beginCaptures: { 0: { name: 'punctuation.section.embedded.begin.php' } },
      end: '(\\?)>|\\z',
      endCaptures: {
        0: { name: 'punctuation.section.embedded.end.php' },
        1: { name: 'source.php' },
      },
      name: 'meta.embedded.block.php',
      contentName: 'source.php',
      patterns: [{ include: '#php-code' }],
    },
  ],
};

const grammar = {
  information_for_contributors: [
    `Generated by tools/build-grammar.js from ${SOURCE}`,
    'Original grammar: https://github.com/KapitanOczywisty/language-php (MIT). See grammars/LICENSE-vscode.txt.',
  ],
  version: php.version,
  name: 'PHP',
  scopeName: 'text.html.php',
  patterns: [
    { begin: '\\A#!', end: '$', name: 'comment.line.shebang.php' },
    { include: '#php-tag' },
    { include: 'text.html.basic' },
  ],
  repository,
};

await writeFile(new URL('../grammars/php.tmLanguage.json', import.meta.url), JSON.stringify(grammar, null, 2) + '\n');
console.log('Wrote grammars/php.tmLanguage.json');
